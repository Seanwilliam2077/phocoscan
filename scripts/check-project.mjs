import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const walk=d=>fs.readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(d,e.name)):[path.join(d,e.name)]);
const ios=path.join(root,'ios');const files=walk(path.join(ios,'PocketWorld'));
const swift=files.filter(x=>x.endsWith('.swift'));
assert(swift.length>5,'Expected native app sources');
const text=swift.map(x=>fs.readFileSync(x,'utf8')).join('\n');
assert(!/\b(WKWebView|UIWebView)\b/.test(text),'Player app must be native');
assert.equal((text.match(/@main\b/g)||[]).length,1,'Exactly one application entry');
assert(text.includes('NativeCaptureView') && text.includes('GaussianSceneView'));
const pbx=fs.readFileSync(path.join(ios,'PocketWorld.xcodeproj/project.pbxproj'),'utf8');
for(const f of swift) assert(pbx.includes(path.relative(ios,f).replaceAll('\\','/')),`Source not in project: ${f}`);
assert(pbx.includes('71ff248e3016ac43c0a9271e322538421b28c360'),'Renderer revision pin missing');
assert(pbx.includes('PocketWorldTests'),'Test target missing');
assert(!fs.readFileSync(path.join(ios,'Config/Info.plist'),'utf8').includes('NSAllowsArbitraryLoads'),'Release must use secure transport');
for(const f of files.filter(x=>x.endsWith('.json'))) JSON.parse(fs.readFileSync(f,'utf8'));
console.log(`Project structural checks passed: ${swift.length} Swift files, native media modules, pinned renderer, JSON resources, Release transport policy.`);
console.log('This is NOT an Xcode compiler, simulator, signing, or physical-device test.');
